// v3.3.516: approved presentation + rollback, driven through real controls.
const {JSDOM}=require('jsdom');
const fs=require('fs'),path=require('path'),vm=require('vm');
const dir=process.argv[2]||'.';
const html=fs.readFileSync(path.join(dir,'index.html'),'utf8');
const css=fs.readFileSync(path.join(dir,'css/app.css'),'utf8');
const dom=new JSDOM(html.replace(/<script[^>]*src=[^>]*><\/script>/g,''),{url:'https://tahros.github.io/showup/',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window,ctx=dom.getInternalVMContext();
w.fetch=()=>Promise.reject(new Error('offline'));
w.matchMedia=()=>({matches:false,addEventListener(){},removeEventListener(){},addListener(){}});
w.scrollTo=()=>{};w.navigator.vibrate=()=>{};
w.HTMLCanvasElement.prototype.getContext=()=>new Proxy({measureText:()=>({width:10})},{get:(o,k)=>k in o?o[k]:()=>({})});
for(const m of html.matchAll(/src="(js\/[^?"]+)\?v=/g)) vm.runInContext(fs.readFileSync(path.join(dir,m[1]),'utf8'),ctx,{filename:m[1]});
const run=s=>vm.runInContext(s,ctx);
let failed=0;
const ok=(name,value)=>{console.log(value?'PASS':'FAIL',name);if(!value)failed++;};
const tap=s=>{const el=w.document.querySelector(s);if(!el)throw Error('Missing control '+s);el.click();};
ok('Body-part rule uses stronger edge ink',/h2\.flow-bodyhead::after\{background:var\(--edge\)/.test(css));
ok('Refined part tiles align to the left',/\[data-flow="refined"\][^\n]*\.partcard\{align-items:flex-start;text-align:left/.test(css));
ok('Last Time header and both groups align centrally',/\[data-flow="refined"\][^\n]*\.partlast>\.lasthead\{[^}]*align-items:center/.test(css)&&/\.partlast>\.lasthead>span\{display:inline-flex;align-items:center/.test(css));
ok('Refined recency is softer readable ink',/\.flow-exgroup \.logmain \.sub\{[^}]*color:var\(--faint\);font-weight:400/.test(css));
ok('Shimmer is on selected tab only, never a backdrop blur',/\[data-flow="refined"\] nav button\.on::after\{[^}]*pointer-events:none[^}]*animation:sheen 6\.8s/.test(css));
ok('Reduced motion disables the tab shimmer',/@media\(prefers-reduced-motion:reduce\)\{\s*:root\[data-flow="refined"\] nav button\.on::after\{animation:none;background:none\}/.test(css));
run(`DB.days={};DB.plan=null;DB.week=null;DB.suggest=null;DB.settings.onboarded='test';DB.settings.unit='lb';d1={step:0,part:null,preview:false};SEED=deriveAll();view='today';render();`);
ok('Refined is the initial layout',run(`refinedFlow() && document.documentElement.dataset.flow==='refined'`));
ok('First visit keeps the first-set path AND Paste/Write',!!w.document.querySelector('[data-d1="start"]')&&!!w.document.querySelector('[data-planpaste]')&&!!w.document.querySelector('[data-planwrite]'));
tap('[data-planpaste]');
const raw='Squat\n  135 lb × 8\n  205 lb × 8 8 8 8\n\nRomanian Deadlift\n  165 lb × 10 10 10\n\nPlank\n  BW × 60 sec × 3';
const area=w.document.querySelector('#planText');area.value=raw;area.dispatchEvent(new w.Event('input',{bubbles:true}));
tap('[data-planread]');
ok('Paste reaches the real parser preview',run(`lift.plan==='preview' && lift.planRows.some(r=>r.ex==='Squat') && lift.planRows.some(r=>r.ex==='Plank')`));
tap('[data-planaccept]');
ok('First visit can see the plan it just saved',!!w.document.querySelector('.plancard')&&!w.document.querySelector('.d1hero'));
ok('Saving a plan does not log a workout',run(`!hasAnyDays()`));
ok('Plan tap has a visual chevron',!!w.document.querySelector('.planrow .ic-chevron'));
const body=w.document.querySelector('[data-planfoldbody]');
tap('[data-planfold]');
ok('Plan fold retains the DOM and makes it inert',body===w.document.querySelector('[data-planfoldbody]')&&body.hasAttribute('inert'));
tap('[data-planfold]');
tap('[data-planex="Squat"] .pn');
ok('Plan opens the real logger and preserves Today return',run(`view==='lift'&&lift.ex==='Squat'&&lift.ret==='today'`));
tap('.back');
ok('Logger back returns to Today',run(`view==='today'`));
run(`DB.days={};for(const n of [2,4,6]){const d=new Date(todayISO+'T00:00');d.setDate(d.getDate()-n);DB.days[d.toLocaleDateString('en-CA')]={w:[{part:'Legs',ex:'Squat',w:60,reps:[8,8],at:1}],upd:1};}DB.plan=null;DB.week=null;DB.suggest=null;SEED=deriveAll();lift={part:'Legs',ex:null};view='lift';render();`);
ok('Train retains all body-part choices',w.document.querySelectorAll('.partcard').length===run(`Object.keys(SEED.catalog).length`));
ok('Train groups readable exercises, without an extra plan',!!w.document.querySelector('.flow-exgroup .logmain')&&!w.document.querySelector('.plancard'));
ok('Body-part heading has a dedicated contrast hook',!!w.document.querySelector('h2.flow-bodyhead'));
ok('Go-to metadata is recency only, not yearly frequency',!w.document.querySelector('.flow-goto').textContent.includes('this year')&&w.document.querySelector('.flow-goto .sub').textContent==='2d ago');
const last=w.document.querySelector('[data-flow-lastbody]'),part=w.document.querySelector('.partgrid');
ok('Last time starts quietly folded',!!last&&last.hasAttribute('inert'));
tap('[data-plfold]');
ok('Last time unfolds without rebuilding the page',last===w.document.querySelector('[data-flow-lastbody]')&&part===w.document.querySelector('.partgrid')&&!last.inert);
run('render()');
ok('Last time remembers its fold',w.document.querySelector('[data-plfold]').getAttribute('aria-expanded')==='true');
run(`view='sync';render();`);
const before=run(`JSON.stringify({days:DB.days,plan:DB.plan,week:DB.week,settings:DB.settings})`);
tap('[data-flowpick="previous"]');
ok('Previous changes only a local presentation key',run(`!refinedFlow() && localStorage.getItem(FLOW_KEY)==='previous'`)&&before===run(`JSON.stringify({days:DB.days,plan:DB.plan,week:DB.week,settings:DB.settings})`));
run(`view='lift';lift.ex=null;render();`);
ok('Previous restores original rows and fold renderer',!w.document.querySelector('.flow-exgroup')&&!w.document.querySelector('[data-flow-lastbody]'));
run(`view='sync';render();`);tap('[data-flowpick="refined"]');
run(`view='lift';render();`);
ok('Refined can be restored without losing the ledger',!!w.document.querySelector('.flow-exgroup')&&before===run(`JSON.stringify({days:DB.days,plan:DB.plan,week:DB.week,settings:DB.settings})`));
run(`view='stats';render();`);
ok('Stats is outside the scoped layout',w.document.querySelector('#view').dataset.flowView==='stats'&&!w.document.querySelector('.flow-exgroup'));
run(`view='today';d1.preview=true;render();`);
ok('Day-one demonstration cannot enter real planning',!w.document.querySelector('[data-planpaste]')&&!w.document.querySelector('[data-planwrite]'));
process.exit(failed?1:0);
